<?php

namespace App\Markdown\Renderers;

use App\Markdown\Format;
use App\Markdown\MarkdownPage;

/**
 * Keep in sync with resources/views/privacy.blade.php (including its "Last updated" date).
 */
class PrivacyPage extends StaticPage
{
    public function pattern(): string
    {
        return '/privacy';
    }

    public function section(): string
    {
        return 'legal';
    }

    public function render(array $params): ?MarkdownPage
    {
        $issues = Format::link('onyedika-glitch/youextractor', config('site.contact.issues'));

        $body = <<<MD
        YouExtractor ("we", "our", or "us") is committed to protecting your privacy. This Privacy Policy explains how we collect, use, and disclose your personal information when you use our service.

        ## 1. Information We Collect

        - **Account Information:** When you log in via Google or GitHub OAuth, we receive your public profile information (such as your name, email address, and avatar URL).
        - **Service Usage:** We collect the YouTube URLs you submit and the code snippets generated by our service.
        - **GitHub Access:** If you choose to push code directly to your GitHub account, we collect and use your GitHub Personal Access Token solely to authenticate the API request to create the repository and push the code on your behalf. We do not store this token on our servers.

        ## 2. How We Use Your Information

        - To provide, operate, and maintain the YouExtractor service.
        - To authenticate you and secure your account.
        - To interact with third-party APIs (Google, GitHub, OpenAI, Gemini, Anthropic) to extract and push code.

        ## 3. Data Sharing

        We do not sell or share your personal data with third parties, except as required to interact with the external APIs mentioned above to perform the code extraction and push requests.

        ## 4. Contact Us

        If you have any questions about this Privacy Policy, please open an issue in our repository: {$issues}
        MD;

        return new MarkdownPage(
            title: 'Privacy Policy',
            summary: "YouExtractor's privacy policy. How we handle your data when you extract code projects from YouTube coding tutorials.",
            path: '/privacy',
            body: $body,
            updated: '2026-06-04',
            related: [['Terms of Service', '/terms']],
        );
    }
}
